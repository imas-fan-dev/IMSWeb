import type { PublicSitePackage } from "@imsweb/contracts/site-packages"

/**
 * Factories for the hosted-site surface. `app/lib/api/endpoints/site-packages.ts`
 * parses `GET /api/site-packages/:slug` with `publicSitePackageSchema`.
 *
 * The slug leads because it arrives as a path parameter, and it also feeds both
 * URLs: the contract types them as full URLs, so they are absolute and share the
 * slug the caller asked for.
 */
export function makePublicSitePackage(
  slug: string,
  overrides: Partial<PublicSitePackage> = {}
): PublicSitePackage {
  const segment = encodeURIComponent(slug)

  return {
    slug,
    title: "偶像大师同好会",
    description: "由站点包托管的静态站点。",
    revisionId: "3f1c1f0e-0f2a-4a6f-9d4f-2b7c1a5e8d30",
    revisionNumber: 1,
    runtimeMode: "safe",
    publishedAt: 1767225600000,
    siteUrl: `https://idol-master.top/sites/${segment}/`,
    contentUrl: `https://objects.example.com/site-content/${segment}/index.html`,
    ...overrides,
  }
}
