import { z } from "@imsweb/contracts/z"

import { adminApiClient } from "../admin-client"
import {
  PUBLIC_CACHE_INVALIDATION_SOURCE,
  STABLE_CONTENT_CACHE_FOR,
} from "../cache-policy"
import { apiClient } from "../client"
import { withBackofficeAuth, withBackofficeCsrf } from "../types"

import {
  publicSitePackageSchema,
  sitePackageDeleteRevisionResultSchema,
  sitePackageListSchema,
  sitePackagePreviewResultSchema,
  sitePackagePublishResultSchema,
  sitePackageUploadResultSchema,
} from "@imsweb/contracts/site-packages"

export * from "@imsweb/contracts/site-packages"

import type {
  PublicSitePackage,
  SitePackageRuntimeMode,
  SitePackageUploadResult,
} from "@imsweb/contracts/site-packages"

export type SitePackageUpload = {
  archive: File
  entryPath: string
  runtimeMode: SitePackageRuntimeMode
}

export type NewSitePackageUpload = SitePackageUpload & {
  slug: string
  title: string
  description: string
}

function appendUploadFields(form: FormData, upload: SitePackageUpload) {
  form.append("entryPath", upload.entryPath)
  form.append("runtimeMode", upload.runtimeMode)
  form.append("archive", upload.archive)
}

export function getSitePackages() {
  return adminApiClient.Get<z.infer<typeof sitePackageListSchema>, unknown>(
    "/api/admin/site-packages",
    {
      meta: withBackofficeAuth(),
      transform: (payload) => sitePackageListSchema.parse(payload),
    }
  )
}

export function getPublicSitePackage(slug: string) {
  return apiClient.Get<PublicSitePackage, unknown>(
    `/api/site-packages/${encodeURIComponent(slug)}`,
    {
      cacheFor: STABLE_CONTENT_CACHE_FOR,
      hitSource: PUBLIC_CACHE_INVALIDATION_SOURCE.sitePackages,
      transform: (payload) => publicSitePackageSchema.parse(payload),
    }
  )
}

export function createSitePackage(upload: NewSitePackageUpload) {
  const form = new FormData()
  form.append("slug", upload.slug)
  form.append("title", upload.title)
  form.append("description", upload.description)
  appendUploadFields(form, upload)
  return adminApiClient.Post<SitePackageUploadResult, unknown>(
    "/api/admin/site-packages",
    form,
    {
      meta: withBackofficeCsrf(),
      transform: (payload) => sitePackageUploadResultSchema.parse(payload),
    }
  )
}

export function createSitePackageRevision(
  packageId: string,
  upload: SitePackageUpload
) {
  const form = new FormData()
  appendUploadFields(form, upload)
  return adminApiClient.Post<SitePackageUploadResult, unknown>(
    `/api/admin/site-packages/${encodeURIComponent(packageId)}/revisions`,
    form,
    {
      meta: withBackofficeCsrf(),
      transform: (payload) => sitePackageUploadResultSchema.parse(payload),
    }
  )
}

export function publishSitePackageRevision(
  packageId: string,
  revisionId: string
) {
  return adminApiClient.Post<
    z.infer<typeof sitePackagePublishResultSchema>,
    unknown
  >(
    `/api/admin/site-packages/${encodeURIComponent(packageId)}/revisions/${encodeURIComponent(revisionId)}/publish`,
    undefined,
    {
      meta: withBackofficeCsrf(),
      name: PUBLIC_CACHE_INVALIDATION_SOURCE.sitePackages,
      transform: (payload) => sitePackagePublishResultSchema.parse(payload),
    }
  )
}

export function deleteSitePackageRevision(
  packageId: string,
  revisionId: string
) {
  return adminApiClient.Delete<
    z.infer<typeof sitePackageDeleteRevisionResultSchema>,
    unknown
  >(
    `/api/admin/site-packages/${encodeURIComponent(packageId)}/revisions/${encodeURIComponent(revisionId)}`,
    undefined,
    {
      meta: withBackofficeCsrf(),
      name: PUBLIC_CACHE_INVALIDATION_SOURCE.sitePackages,
      transform: (payload) =>
        sitePackageDeleteRevisionResultSchema.parse(payload),
    }
  )
}

export function rotateSitePackagePreviewToken(
  packageId: string,
  revisionId: string
) {
  return adminApiClient.Post<
    z.infer<typeof sitePackagePreviewResultSchema>,
    unknown
  >(
    `/api/admin/site-packages/${encodeURIComponent(packageId)}/revisions/${encodeURIComponent(revisionId)}/preview-token`,
    undefined,
    {
      meta: withBackofficeCsrf(),
      transform: (payload) => sitePackagePreviewResultSchema.parse(payload),
    }
  )
}
