import { publicSitePackageSchema } from "@imsweb/contracts/site-packages"
import { describe, expect, it } from "vitest"

import { assertFactoryCoversSchema } from "@/mocks/data/schema-conformance"
import { makePublicSitePackage } from "@/mocks/data/site-packages"

describe("site package fixture factories", () => {
  it("builds a site package that matches its contract", () => {
    const value = makePublicSitePackage("demo-site")

    assertFactoryCoversSchema(publicSitePackageSchema, value)
    expect(publicSitePackageSchema.parse(value)).toEqual(value)
  })

  it("carries the requested slug into both URLs", () => {
    const value = makePublicSitePackage("demo-site")

    expect(value.slug).toBe("demo-site")
    expect(value.siteUrl).toContain("demo-site")
    expect(value.contentUrl).toContain("demo-site")
  })

  it("encodes a slug that is not URL safe", () => {
    const value = makePublicSitePackage("a b/c")

    expect(value.slug).toBe("a b/c")
    expect(value.siteUrl).toBe("https://idol-master.top/sites/a%20b%2Fc/")
    assertFactoryCoversSchema(publicSitePackageSchema, value)
    expect(publicSitePackageSchema.parse(value)).toEqual(value)
  })

  it("layers overrides over the defaults", () => {
    const value = makePublicSitePackage("demo-site", {
      runtimeMode: "isolated-script",
      revisionNumber: 4,
    })

    expect(value.runtimeMode).toBe("isolated-script")
    expect(value.revisionNumber).toBe(4)
    assertFactoryCoversSchema(publicSitePackageSchema, value)
    expect(publicSitePackageSchema.parse(value)).toEqual(value)
  })
})
