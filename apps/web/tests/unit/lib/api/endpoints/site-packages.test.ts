import { afterEach, describe, expect, it, vi } from "vitest"

import type {
  NewSitePackageUpload,
  SitePackageUpload,
} from "~/lib/api/endpoints/site-packages"

const API_ORIGIN = "https://api.imsweb.test"
const PACKAGE_ID = "11111111-1111-4111-8111-111111111111"
const REVISION_ID = "22222222-2222-4222-8222-222222222222"

const uploadFields = {
  previewUrl: "https://main.imsweb.test/site-content/_preview/token/",
  previewToken: "token",
  warnings: ["script disabled"],
  hasScripts: true,
}

const revision = {
  id: REVISION_ID,
  packageId: PACKAGE_ID,
  revisionNumber: 1,
  entryPath: "index.html",
  runtimeMode: "safe" as const,
  state: "ready" as const,
  fileCount: 1,
  totalBytes: 1,
  sourceSha256: "a".repeat(64),
  createdBy: 1,
  createdAt: 1,
  publishedAt: null,
}

async function loadSitePackageEndpoint() {
  vi.resetModules()
  vi.stubEnv("VITE_IMS_API_ORIGIN", API_ORIGIN)
  vi.stubEnv("VITE_IMS_APP_TARGET", "app")
  return import("~/lib/api/endpoints/site-packages")
}

afterEach(() => {
  vi.unstubAllEnvs()
  vi.unstubAllGlobals()
  vi.resetModules()
})

describe("site-package API contracts", () => {
  it("keeps create and create-revision response payloads exact and distinct", async () => {
    document.cookie = "csrf_token=site-package-contract-csrf; path=/"
    const created = {
      success: true as const,
      packageId: PACKAGE_ID,
      revisionId: REVISION_ID,
      ...uploadFields,
    }
    const createdRevision = {
      success: true as const,
      revision,
      ...uploadFields,
    }
    const fetchMock = vi
      .fn<typeof fetch>()
      .mockResolvedValueOnce(Response.json(created, { status: 201 }))
      .mockResolvedValueOnce(Response.json(createdRevision, { status: 201 }))
      .mockResolvedValueOnce(Response.json(createdRevision, { status: 201 }))
      .mockResolvedValueOnce(Response.json(created, { status: 201 }))
    vi.stubGlobal("fetch", fetchMock)

    const { createSitePackage, createSitePackageRevision } =
      await loadSitePackageEndpoint()
    const archive = new File(["site package"], "site.zip", {
      type: "application/zip",
    })
    const revisionUpload = {
      archive,
      entryPath: "index.html",
      runtimeMode: "safe",
    } satisfies SitePackageUpload
    const createUpload = {
      ...revisionUpload,
      slug: "site-package",
      title: "Site package",
      description: "Package contract test",
    } satisfies NewSitePackageUpload

    await expect(createSitePackage(createUpload).send()).resolves.toEqual(
      created
    )
    await expect(
      createSitePackageRevision(PACKAGE_ID, revisionUpload).send()
    ).resolves.toEqual(createdRevision)
    await expect(createSitePackage(createUpload).send()).rejects.toMatchObject({
      kind: "contract",
      code: "CONTRACT_VIOLATION",
      payload: createdRevision,
    })
    await expect(
      createSitePackageRevision(PACKAGE_ID, revisionUpload).send()
    ).rejects.toMatchObject({
      kind: "contract",
      code: "CONTRACT_VIOLATION",
      payload: created,
    })

    expect(
      fetchMock.mock.calls.map(([input, init]) => [
        new URL(String(input)).pathname,
        init?.method,
      ])
    ).toEqual([
      ["/api/admin/site-packages", "POST"],
      [`/api/admin/site-packages/${PACKAGE_ID}/revisions`, "POST"],
      ["/api/admin/site-packages", "POST"],
      [`/api/admin/site-packages/${PACKAGE_ID}/revisions`, "POST"],
    ])
  })

  it("validates shared HTTP errors before exposing site-package failures", async () => {
    vi.stubGlobal(
      "fetch",
      vi
        .fn<typeof fetch>()
        .mockResolvedValueOnce(
          Response.json({ error: "站点包不存在" }, { status: 404 })
        )
        .mockResolvedValueOnce(
          Response.json(
            { error: "站点包不存在", unexpected: true },
            { status: 404 }
          )
        )
        .mockResolvedValueOnce(
          Response.json({ message: "无权限（仅op可访问）" }, { status: 403 })
        )
    )
    const { getPublicSitePackage } = await loadSitePackageEndpoint()

    await expect(getPublicSitePackage("missing").send()).rejects.toMatchObject({
      kind: "http",
      status: 404,
      payload: { error: "站点包不存在" },
    })
    await expect(
      getPublicSitePackage("missing-again").send()
    ).rejects.toMatchObject({
      kind: "contract",
      status: 404,
      code: "CONTRACT_VIOLATION",
      payload: { error: "站点包不存在", unexpected: true },
    })
    await expect(
      getPublicSitePackage("public-only").send()
    ).rejects.toMatchObject({
      kind: "contract",
      status: 403,
      code: "CONTRACT_VIOLATION",
    })
  })
})
