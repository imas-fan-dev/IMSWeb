-- Readers can report a published card from the wall. Reports outlive the
-- handling so the trail (who reported what, who decided, and why) stays
-- auditable.

CREATE TABLE IF NOT EXISTS public.namecard_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id TEXT NOT NULL REFERENCES public.fudaba_cards (id) ON DELETE CASCADE,
    reporter_account_id TEXT NOT NULL,
    reason TEXT NOT NULL,
    detail TEXT,
    status TEXT NOT NULL DEFAULT 'pending',
    handled_by TEXT,
    handled_at TIMESTAMPTZ,
    resolution_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT namecard_feedback_reason_check
        CHECK (reason IN ('info-error', 'ownership-error', 'content-violation')),
    CONSTRAINT namecard_feedback_status_check
        CHECK (status IN ('pending', 'accepted', 'rejected')),
    CONSTRAINT namecard_feedback_detail_check
        CHECK (detail IS NULL OR char_length(detail) <= 400),
    CONSTRAINT namecard_feedback_note_check
        CHECK (
            resolution_note IS NULL OR char_length(resolution_note) <= 400
        ),
    CONSTRAINT namecard_feedback_resolution_check
        CHECK ((status = 'pending') = (handled_by IS NULL AND handled_at IS NULL))
);

CREATE INDEX IF NOT EXISTS namecard_feedback_queue_idx
    ON public.namecard_feedback (status, created_at);
CREATE INDEX IF NOT EXISTS namecard_feedback_card_idx
    ON public.namecard_feedback (card_id, status);

-- The reporter hears about the decision through the same notice feed the
-- owner uses.
ALTER TABLE public.namecard_notifications
    DROP CONSTRAINT namecard_notifications_kind_check;
ALTER TABLE public.namecard_notifications
    ADD CONSTRAINT namecard_notifications_kind_check
        CHECK (kind IN (
            'card-approved', 'card-rejected', 'claim-approved', 'claim-rejected',
            'station-message', 'card-locked', 'card-unlocked',
            'card-admin-edited', 'card-transferred-in', 'card-transferred-out',
            'card-feedback-accepted', 'card-feedback-rejected'
        ));
