-- ims:migration-phase: post-data
--
-- Wiki 增强 Markdown 文档媒体与共享封面引用（Ticket 03）。
--
-- `wiki_entry_document_media` 保存条目自己上传的文档图片。`object_key` 是对象
-- 存储里的真实键，唯一约束让同一张图不会被登记两次；行删除时对象由应用侧的
-- 补偿清理负责，数据库只保证元数据与对象键一一对应。
--
-- `wiki_entry_document_cover_refs` 记录文档对企划共享封面素材
-- （`wiki_story_cover_assets`）的引用。复合外键
-- `(cover_asset_id, project_id) -> (id, agency_id)` 与既有
-- `wiki_story_cards` 的外键口径一致：跨企划引用在数据库层就被拒绝，
-- `ON DELETE RESTRICT` 保证仍被文档引用的素材不能删除。

-- The migration runner applies the whole catalog in one transaction. Earlier
-- data migrations update `wiki_entries` rows, which queues the deferred
-- `wiki_entry_name_integrity` constraint trigger; PostgreSQL refuses the
-- foreign keys below (they lock `wiki_entries`) while such an event is pending.
-- Flushing the queue first is safe here, then the deferred mode is restored for
-- later migrations in the same catalog run.
SET CONSTRAINTS ALL IMMEDIATE;

CREATE TABLE public.wiki_entry_document_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    entry_id BIGINT NOT NULL REFERENCES public.wiki_entries(id) ON DELETE CASCADE,
    object_key TEXT NOT NULL UNIQUE,
    alt_text TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX wiki_entry_document_media_entry_idx
    ON public.wiki_entry_document_media (entry_id);

CREATE INDEX wiki_entry_document_media_project_idx
    ON public.wiki_entry_document_media (project_id);

CREATE TABLE public.wiki_entry_document_cover_refs (
    entry_id BIGINT NOT NULL REFERENCES public.wiki_entry_documents(entry_id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL,
    cover_asset_id BIGINT NOT NULL,
    PRIMARY KEY (entry_id, cover_asset_id),
    FOREIGN KEY (cover_asset_id, project_id)
        REFERENCES public.wiki_story_cover_assets(id, agency_id)
        ON DELETE RESTRICT
);

CREATE INDEX wiki_entry_document_cover_refs_asset_idx
    ON public.wiki_entry_document_cover_refs (cover_asset_id);

COMMENT ON TABLE public.wiki_entry_document_media IS
    'Images uploaded for one Wiki entry Enhanced Markdown document.';
COMMENT ON TABLE public.wiki_entry_document_cover_refs IS
    'Agency shared cover assets referenced by one entry document.';

SET CONSTRAINTS ALL DEFERRED;
