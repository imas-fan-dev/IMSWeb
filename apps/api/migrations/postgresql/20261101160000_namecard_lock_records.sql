-- An audit trail for lock decisions. Locking appends a row, unlocking deletes
-- it, and a hard-deleted card takes its rows with it, so the table always
-- answers "which cards are locked right now, by whom and why".
CREATE TABLE IF NOT EXISTS public.namecard_lock_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id TEXT NOT NULL REFERENCES public.fudaba_cards(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    handled_by TEXT,
    locked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT namecard_lock_records_reason_check
        CHECK (length(btrim(reason)) >= 1 AND length(btrim(reason)) <= 400),
    CONSTRAINT namecard_lock_records_handled_by_check
        CHECK (handled_by IS NULL OR length(btrim(handled_by)) BETWEEN 1 AND 80)
);

CREATE INDEX IF NOT EXISTS namecard_lock_records_locked_at_idx
    ON public.namecard_lock_records (locked_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS namecard_lock_records_card_idx
    ON public.namecard_lock_records (card_id);

-- Cards locked before this table existed keep their trail, with the operator
-- left unknown because the old flow never stored one.
INSERT INTO public.namecard_lock_records (card_id, reason, handled_by, locked_at)
SELECT card.id,
       COALESCE(NULLIF(btrim(card.lock_reason), ''), '未记录理由'),
       NULL,
       card.updated_at
  FROM public.fudaba_cards card
 WHERE card.publication_status = 'locked'
   AND card.deleted_at IS NULL
   AND NOT EXISTS (
       SELECT 1 FROM public.namecard_lock_records record WHERE record.card_id = card.id
   );

CREATE INDEX IF NOT EXISTS namecard_feedback_handled_at_idx
    ON public.namecard_feedback (handled_at DESC, id DESC);
