CREATE TABLE public.chronicle_entries (
    article_id BIGINT PRIMARY KEY,
    occurred_on DATE,
    ended_on DATE,
    date_precision TEXT,
    source_type TEXT,
    source_event_id BIGINT,
    location TEXT,
    timeline_order INTEGER NOT NULL DEFAULT 0,
    live_source_id TEXT,
    live_title TEXT,
    live_date TEXT,
    live_time TEXT,
    live_location TEXT,
    live_detail_url TEXT,
    live_franchises JSONB NOT NULL DEFAULT '[]'::jsonb,
    live_brand_codes JSONB NOT NULL DEFAULT '[]'::jsonb,
    CONSTRAINT chronicle_entries_article_id_fkey
        FOREIGN KEY (article_id) REFERENCES public.articles(id) ON DELETE CASCADE,
    CONSTRAINT chronicle_entries_date_precision_check
        CHECK (date_precision IS NULL OR date_precision IN ('year', 'month', 'day')),
    CONSTRAINT chronicle_entries_source_type_check
        CHECK (source_type IS NULL OR source_type IN ('official', 'community')),
    CONSTRAINT chronicle_entries_date_range_check
        CHECK (ended_on IS NULL OR occurred_on IS NULL OR ended_on >= occurred_on),
    CONSTRAINT chronicle_entries_timeline_order_check
        CHECK (timeline_order >= 0),
    CONSTRAINT chronicle_entries_source_event_fkey
        FOREIGN KEY (source_event_id) REFERENCES public.events(id) ON DELETE SET NULL
