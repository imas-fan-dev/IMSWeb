CREATE TABLE public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type TEXT NOT NULL,
    title TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    cover_url TEXT,
    body_json JSONB NOT NULL DEFAULT '{"type":"doc","content":[]}'::jsonb,
    body_html TEXT NOT NULL DEFAULT '',
    body_schema_version INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'draft',
    revision INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT,
    updated_by BIGINT,
    published_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    CONSTRAINT articles_content_type_check
        CHECK (content_type IN ('event', 'chronicle')),
    CONSTRAINT articles_status_check
        CHECK (status IN ('draft', 'published', 'archived')),
    CONSTRAINT articles_revision_check
        CHECK (revision >= 0),
    CONSTRAINT articles_body_schema_version_check
        CHECK (body_schema_version >= 1),
    CONSTRAINT articles_created_by_fkey
        FOREIGN KEY (created_by) REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT articles_updated_by_fkey
        FOREIGN KEY (updated_by) REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT articles_published_by_fkey
        FOREIGN KEY (published_by) REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX articles_public_type_idx
    ON public.articles (content_type, status, published_at DESC, id DESC);

CREATE INDEX articles_updated_idx
    ON public.articles (status, updated_at DESC, id DESC);

