-- Only unambiguous, same-project names are imported automatically. Everything
-- else remains an independent Wiki entry until explicitly bound by an editor.
CREATE TEMP TABLE catalog_entry_import ON COMMIT DROP AS
SELECT e.id AS entry_id, min(c.id) AS character_id
FROM wiki_entries e JOIN catalog_characters c
  ON c.default_project_id=e.project_id
 AND (lower(c.name_cn)=lower(replace(e.local_name_cn,'・','·')) OR (
     e.project_id=(SELECT id FROM projects WHERE code='876')
     AND e.local_name_cn='秋月凉' AND c.name_ja='秋月涼'
 ))
 AND c.deleted_at IS NULL AND NOT c.is_fallback
WHERE e.deleted_at IS NULL
GROUP BY e.id HAVING count(*)=1;
DELETE FROM catalog_entry_import m USING (
    SELECT i.character_id,e.project_id FROM catalog_entry_import i
    JOIN wiki_entries e ON e.id=i.entry_id GROUP BY i.character_id,e.project_id HAVING count(*)>1
) duplicates, wiki_entries e
WHERE m.entry_id=e.id AND m.character_id=duplicates.character_id AND e.project_id=duplicates.project_id;

UPDATE catalog_character_project_profiles p SET name_cn=CASE WHEN e.local_name_cn=(SELECT name_cn FROM catalog_characters WHERE id=p.character_id) THEN NULL ELSE e.local_name_cn END,
    representative_color=e.local_accent_color,avatar_object_key=e.local_image_object_key,
    avatar_fit=e.local_image_fit,avatar_focal_x=e.local_image_focal_x,avatar_focal_y=e.local_image_focal_y,
    avatar_zoom=e.local_image_zoom,avatar_rotation=e.local_image_rotation,avatar_media_revision=e.local_image_media_revision
FROM catalog_entry_import m JOIN wiki_entries e ON e.id=m.entry_id
WHERE p.character_id=m.character_id AND p.project_id=e.project_id;
UPDATE wiki_entries e SET character_profile_id=p.id FROM catalog_entry_import m
JOIN catalog_character_project_profiles p ON p.character_id=m.character_id
WHERE e.id=m.entry_id AND p.project_id=e.project_id;

CREATE TEMP TABLE catalog_group_entry_import ON COMMIT DROP AS
SELECT e.id AS entry_id,min(p.id) AS profile_id FROM wiki_entries e
JOIN catalog_group_project_profiles p ON p.project_id=e.project_id
JOIN catalog_groups g ON g.id=p.group_id AND (
    lower(g.name_cn)=lower(e.local_name_cn) OR lower(g.name_ja)=lower(e.local_name_cn)
    OR (e.project_id=(SELECT id FROM projects WHERE code='sidem') AND
        (e.local_name_cn,g.name_cn) IN (('Café Parade','CafeParade'),('THE 虎牙道','THE虎牙道')))
)
WHERE e.character_profile_id IS NULL AND e.deleted_at IS NULL AND g.deleted_at IS NULL
  AND e.entry_kind='unit'
GROUP BY e.id HAVING count(*)=1;
DELETE FROM catalog_group_entry_import m USING (
    SELECT profile_id FROM catalog_group_entry_import GROUP BY profile_id HAVING count(*)>1
) duplicates WHERE m.profile_id=duplicates.profile_id;
UPDATE catalog_group_project_profiles p SET name_cn=CASE WHEN e.local_name_cn=(SELECT name_cn FROM catalog_groups WHERE id=p.group_id) THEN NULL ELSE e.local_name_cn END,color=e.local_accent_color,
    image_object_key=e.local_image_object_key,image_fit=e.local_image_fit,image_focal_x=e.local_image_focal_x,
    image_focal_y=e.local_image_focal_y,image_zoom=e.local_image_zoom,image_rotation=e.local_image_rotation,
    image_media_revision=e.local_image_media_revision
FROM catalog_group_entry_import m JOIN wiki_entries e ON e.id=m.entry_id WHERE p.id=m.profile_id;
UPDATE wiki_entries e SET group_profile_id=m.profile_id FROM catalog_group_entry_import m WHERE e.id=m.entry_id;

-- ML explicitly reuses the original 765 cast. Require an already resolved 765
-- entry as evidence; same-name people from DS, SideM and XENO are not merged.
CREATE TEMP TABLE catalog_shared_cast_import ON COMMIT DROP AS
SELECT target.id AS entry_id,min(source_profile.character_id) AS character_id
FROM wiki_entries target JOIN projects target_project ON target_project.id=target.project_id AND target_project.code='ml'
JOIN wiki_entries source ON lower(source.local_name_cn)=lower(target.local_name_cn)
JOIN projects source_project ON source_project.id=source.project_id AND source_project.code='765'
JOIN catalog_character_project_profiles source_profile ON source_profile.id=source.character_profile_id
JOIN catalog_characters character ON character.id=source_profile.character_id
WHERE target.character_profile_id IS NULL AND target.group_profile_id IS NULL
  AND target.deleted_at IS NULL AND source.deleted_at IS NULL AND character.deleted_at IS NULL
  AND NOT character.is_fallback AND target.entry_kind='idol'
GROUP BY target.id HAVING count(*)=1;
INSERT INTO catalog_character_project_profiles(character_id,project_id)
SELECT m.character_id,e.project_id FROM catalog_shared_cast_import m JOIN wiki_entries e ON e.id=m.entry_id
ON CONFLICT (character_id,project_id) DO NOTHING;
UPDATE catalog_character_project_profiles p SET name_cn=CASE WHEN e.local_name_cn=(SELECT name_cn FROM catalog_characters WHERE id=p.character_id) THEN NULL ELSE e.local_name_cn END,
    representative_color=e.local_accent_color,avatar_object_key=e.local_image_object_key,
    avatar_fit=e.local_image_fit,avatar_focal_x=e.local_image_focal_x,avatar_focal_y=e.local_image_focal_y,
    avatar_zoom=e.local_image_zoom,avatar_rotation=e.local_image_rotation,avatar_media_revision=e.local_image_media_revision
FROM catalog_shared_cast_import m JOIN wiki_entries e ON e.id=m.entry_id
WHERE p.character_id=m.character_id AND p.project_id=e.project_id;
UPDATE wiki_entries e SET character_profile_id=p.id FROM catalog_shared_cast_import m
JOIN catalog_character_project_profiles p ON p.character_id=m.character_id
WHERE e.id=m.entry_id AND e.project_id=p.project_id;

UPDATE catalog_groups g SET kind='attribute' WHERE EXISTS (
