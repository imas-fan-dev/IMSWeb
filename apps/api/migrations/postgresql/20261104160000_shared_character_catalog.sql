-- Public story lookup still uses project + displayed name. Inherited names
-- must therefore preserve the same uniqueness guarantee as local Wiki names.
-- A project row lock serializes competing name changes without changing IDs
-- or introducing a new public route parameter.
CREATE FUNCTION wiki_check_effective_entry_names(target_project_id BIGINT) RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
    PERFORM id FROM projects WHERE id=target_project_id FOR NO KEY UPDATE;
    IF EXISTS (
        SELECT 1 FROM idols WHERE agency_id=target_project_id AND deleted_at IS NULL
        GROUP BY name_cn HAVING count(*)>1
    ) OR EXISTS (
        SELECT 1 FROM idols current_entry JOIN wiki_entries legacy
            ON legacy.project_id=current_entry.agency_id AND legacy.local_name_cn=current_entry.name_cn
        WHERE current_entry.agency_id=target_project_id AND current_entry.deleted_at IS NULL
            AND legacy.id<>current_entry.id
    ) THEN
        RAISE EXCEPTION 'duplicate effective Wiki entry name'
            USING ERRCODE='23505', CONSTRAINT='wiki_entries_effective_name_key';
    END IF;
END $$;

CREATE FUNCTION wiki_check_entry_name_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='UPDATE' AND (OLD.project_id,OLD.local_name_cn,OLD.character_profile_id,OLD.group_profile_id,OLD.deleted_at)
        IS NOT DISTINCT FROM (NEW.project_id,NEW.local_name_cn,NEW.character_profile_id,NEW.group_profile_id,NEW.deleted_at) THEN
        RETURN NULL;
    END IF;
    PERFORM wiki_check_effective_entry_names(NEW.project_id);
    IF TG_OP='UPDATE' AND OLD.project_id<>NEW.project_id THEN
        PERFORM wiki_check_effective_entry_names(OLD.project_id);
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER wiki_entry_name_integrity
AFTER INSERT OR UPDATE OF project_id,local_name_cn,character_profile_id,group_profile_id,deleted_at ON wiki_entries
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION wiki_check_entry_name_change();

CREATE FUNCTION wiki_check_catalog_name_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE target BIGINT;
BEGIN
    FOR target IN SELECT DISTINCT e.project_id FROM wiki_entries e
        LEFT JOIN catalog_character_project_profiles cp ON cp.id=e.character_profile_id
        LEFT JOIN catalog_group_project_profiles gp ON gp.id=e.group_profile_id
        WHERE e.deleted_at IS NULL AND (
            TG_TABLE_NAME='catalog_characters' AND cp.character_id=NEW.id
            OR TG_TABLE_NAME='catalog_groups' AND gp.group_id=NEW.id
            OR TG_TABLE_NAME='catalog_character_project_profiles' AND cp.id=NEW.id
            OR TG_TABLE_NAME='catalog_group_project_profiles' AND gp.id=NEW.id
        ) ORDER BY e.project_id
    LOOP
        PERFORM wiki_check_effective_entry_names(target);
    END LOOP;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER wiki_character_name_integrity AFTER UPDATE OF name_cn ON catalog_characters
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (OLD.name_cn IS DISTINCT FROM NEW.name_cn)
EXECUTE FUNCTION wiki_check_catalog_name_change();
CREATE CONSTRAINT TRIGGER wiki_group_name_integrity AFTER UPDATE OF name_cn ON catalog_groups
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (OLD.name_cn IS DISTINCT FROM NEW.name_cn)
EXECUTE FUNCTION wiki_check_catalog_name_change();
CREATE CONSTRAINT TRIGGER wiki_character_profile_name_integrity AFTER UPDATE OF name_cn ON catalog_character_project_profiles
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (OLD.name_cn IS DISTINCT FROM NEW.name_cn)
EXECUTE FUNCTION wiki_check_catalog_name_change();
CREATE CONSTRAINT TRIGGER wiki_group_profile_name_integrity AFTER UPDATE OF name_cn ON catalog_group_project_profiles
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (OLD.name_cn IS DISTINCT FROM NEW.name_cn)
EXECUTE FUNCTION wiki_check_catalog_name_change();

