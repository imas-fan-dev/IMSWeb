FROM wiki_navigation_groups n LEFT JOIN catalog_group_project_profiles p ON p.id=n.group_profile_id
LEFT JOIN catalog_groups g ON g.id=p.group_id;

CREATE FUNCTION wiki_legacy_navigation_write() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE bound BOOLEAN;
BEGIN
    IF TG_OP='INSERT' THEN
        INSERT INTO wiki_navigation_groups(id,project_id,code,name,color,icon_object_key,
            icon_fit,icon_focal_x,icon_focal_y,icon_zoom,icon_rotation,icon_media_revision,display_order,is_fallback)
        VALUES (COALESCE(NEW.id,nextval('wiki_navigation_groups_id_seq')),NEW.agency_id,NEW.code,NEW.name,NEW.color,
