            COALESCE(NEW.icon_focal_y,0.5),COALESCE(NEW.icon_zoom,1),COALESCE(NEW.icon_rotation,0),
            COALESCE(NEW.icon_media_revision,0),COALESCE(NEW.display_order,0),COALESCE(NEW.is_fallback,FALSE))
        RETURNING id INTO NEW.id;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' THEN
        DELETE FROM wiki_navigation_groups WHERE id=OLD.id;
        RETURN OLD;
    END IF;
    SELECT group_profile_id IS NOT NULL INTO bound FROM wiki_navigation_groups WHERE id=OLD.id FOR UPDATE;
    IF bound AND (NEW.name,NEW.color,NEW.icon_object_key,NEW.icon_fit,NEW.icon_focal_x,NEW.icon_focal_y,
        NEW.icon_zoom,NEW.icon_rotation) IS DISTINCT FROM (OLD.name,OLD.color,OLD.icon_object_key,
        OLD.icon_fit,OLD.icon_focal_x,OLD.icon_focal_y,OLD.icon_zoom,OLD.icon_rotation) THEN
        RAISE EXCEPTION 'Bound navigation presentation is owned by the catalog' USING ERRCODE='23514';
    END IF;
    UPDATE wiki_navigation_groups SET code=NEW.code,
        name=CASE WHEN bound THEN name ELSE NEW.name END,color=CASE WHEN bound THEN color ELSE NEW.color END,
        icon_object_key=CASE WHEN bound THEN icon_object_key ELSE NEW.icon_object_key END,
        icon_fit=CASE WHEN bound THEN icon_fit ELSE NEW.icon_fit END,
        icon_focal_x=CASE WHEN bound THEN icon_focal_x ELSE NEW.icon_focal_x END,
        icon_focal_y=CASE WHEN bound THEN icon_focal_y ELSE NEW.icon_focal_y END,
        icon_zoom=CASE WHEN bound THEN icon_zoom ELSE NEW.icon_zoom END,
        icon_rotation=CASE WHEN bound THEN icon_rotation ELSE NEW.icon_rotation END,
        icon_media_revision=CASE WHEN bound THEN icon_media_revision ELSE NEW.icon_media_revision END,
        display_order=NEW.display_order,is_fallback=NEW.is_fallback WHERE id=OLD.id;
    RETURN NEW;
END $$;
