CREATE VIEW idols AS
SELECT e.id, e.project_id AS agency_id,
    CASE WHEN cp.id IS NOT NULL THEN COALESCE(cp.name_cn,c.name_cn)
         WHEN gp.id IS NOT NULL THEN COALESCE(gp.name_cn,g.name_cn) ELSE e.local_name_cn END AS name_cn,
    e.storage_slug AS folder_name,
    CASE WHEN cp.id IS NOT NULL THEN cp.representative_color
         WHEN gp.id IS NOT NULL THEN gp.color ELSE e.local_accent_color END AS color,
    e.is_visible AS wiki_enabled, e.display_order, e.text_color, e.wiki_url,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_object_key WHEN gp.id IS NOT NULL THEN gp.image_object_key ELSE e.local_image_object_key END AS avatar_object_key,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_fit WHEN gp.id IS NOT NULL THEN gp.image_fit ELSE e.local_image_fit END AS avatar_fit,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_focal_x WHEN gp.id IS NOT NULL THEN gp.image_focal_x ELSE e.local_image_focal_x END AS avatar_focal_x,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_focal_y WHEN gp.id IS NOT NULL THEN gp.image_focal_y ELSE e.local_image_focal_y END AS avatar_focal_y,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_zoom WHEN gp.id IS NOT NULL THEN gp.image_zoom ELSE e.local_image_zoom END AS avatar_zoom,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_rotation WHEN gp.id IS NOT NULL THEN gp.image_rotation ELSE e.local_image_rotation END AS avatar_rotation,
    CASE WHEN cp.id IS NOT NULL THEN cp.avatar_media_revision WHEN gp.id IS NOT NULL THEN gp.image_media_revision ELSE e.local_image_media_revision END AS avatar_media_revision,
    e.entry_kind, e.entry_subtype, e.deleted_at
FROM wiki_entries e
LEFT JOIN catalog_character_project_profiles cp ON cp.id=e.character_profile_id
LEFT JOIN catalog_characters c ON c.id=cp.character_id
LEFT JOIN catalog_group_project_profiles gp ON gp.id=e.group_profile_id
LEFT JOIN catalog_groups g ON g.id=gp.group_id;

CREATE FUNCTION wiki_legacy_entry_write() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE bound BOOLEAN; current_revision INTEGER;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO wiki_entries(id, project_id, local_name_cn, storage_slug, local_accent_color,
            is_visible, display_order, text_color, wiki_url, local_image_object_key, local_image_fit,
            local_image_focal_x, local_image_focal_y, local_image_zoom, local_image_rotation, local_image_media_revision,
            entry_kind, entry_subtype, deleted_at)
        VALUES (COALESCE(NEW.id,nextval('wiki_entries_id_seq')),NEW.agency_id,NEW.name_cn,NEW.folder_name,NEW.color,
            COALESCE(NEW.wiki_enabled,TRUE),COALESCE(NEW.display_order,0),COALESCE(NEW.text_color,'#FFFFFF'),NEW.wiki_url,
            NEW.avatar_object_key,COALESCE(NEW.avatar_fit,'cover'),COALESCE(NEW.avatar_focal_x,0.5),
            COALESCE(NEW.avatar_focal_y,0.5),COALESCE(NEW.avatar_zoom,1),COALESCE(NEW.avatar_rotation,0),
            COALESCE(NEW.avatar_media_revision,0),COALESCE(NEW.entry_kind,'idol'),NEW.entry_subtype,NEW.deleted_at)
        RETURNING id INTO NEW.id;
        RETURN NEW;
    END IF;
    SELECT character_profile_id IS NOT NULL OR group_profile_id IS NOT NULL,local_image_media_revision
        INTO bound,current_revision
        FROM wiki_entries WHERE id=OLD.id FOR UPDATE;
    IF TG_OP='DELETE' THEN
        DELETE FROM wiki_entries WHERE id=OLD.id;
        RETURN OLD;
    END IF;
    IF bound AND (NEW.name_cn,NEW.color,NEW.avatar_object_key,NEW.avatar_fit,NEW.avatar_focal_x,
        NEW.avatar_focal_y,NEW.avatar_zoom,NEW.avatar_rotation) IS DISTINCT FROM
        (OLD.name_cn,OLD.color,OLD.avatar_object_key,OLD.avatar_fit,OLD.avatar_focal_x,
        OLD.avatar_focal_y,OLD.avatar_zoom,OLD.avatar_rotation) THEN
        RAISE EXCEPTION 'Bound entry presentation is owned by the catalog' USING ERRCODE='23514';
    END IF;
    IF NOT bound AND NEW.avatar_media_revision IS DISTINCT FROM OLD.avatar_media_revision
        AND current_revision<>OLD.avatar_media_revision THEN RETURN NULL; END IF;
    UPDATE wiki_entries SET
        local_name_cn=CASE WHEN bound THEN local_name_cn ELSE NEW.name_cn END,
        local_accent_color=CASE WHEN bound THEN local_accent_color ELSE NEW.color END,
        local_image_object_key=CASE WHEN bound OR NEW.avatar_object_key IS NOT DISTINCT FROM OLD.avatar_object_key THEN local_image_object_key ELSE NEW.avatar_object_key END,
        local_image_fit=CASE WHEN bound OR NEW.avatar_fit IS NOT DISTINCT FROM OLD.avatar_fit THEN local_image_fit ELSE NEW.avatar_fit END,
        local_image_focal_x=CASE WHEN bound OR NEW.avatar_focal_x IS NOT DISTINCT FROM OLD.avatar_focal_x THEN local_image_focal_x ELSE NEW.avatar_focal_x END,
        local_image_focal_y=CASE WHEN bound OR NEW.avatar_focal_y IS NOT DISTINCT FROM OLD.avatar_focal_y THEN local_image_focal_y ELSE NEW.avatar_focal_y END,
        local_image_zoom=CASE WHEN bound OR NEW.avatar_zoom IS NOT DISTINCT FROM OLD.avatar_zoom THEN local_image_zoom ELSE NEW.avatar_zoom END,
        local_image_rotation=CASE WHEN bound OR NEW.avatar_rotation IS NOT DISTINCT FROM OLD.avatar_rotation THEN local_image_rotation ELSE NEW.avatar_rotation END,
        local_image_media_revision=CASE WHEN bound OR NEW.avatar_media_revision IS NOT DISTINCT FROM OLD.avatar_media_revision THEN local_image_media_revision ELSE NEW.avatar_media_revision END,
        is_visible=NEW.wiki_enabled,display_order=NEW.display_order,text_color=NEW.text_color,
        wiki_url=NEW.wiki_url,entry_kind=NEW.entry_kind,entry_subtype=NEW.entry_subtype,deleted_at=NEW.deleted_at
    WHERE id=OLD.id;
    RETURN NEW;
END $$;
CREATE TRIGGER wiki_legacy_entry_write INSTEAD OF INSERT OR UPDATE OR DELETE ON idols
FOR EACH ROW EXECUTE FUNCTION wiki_legacy_entry_write();

CREATE VIEW wiki_groups AS
SELECT n.id,n.project_id AS agency_id,n.code,
    CASE WHEN p.id IS NOT NULL THEN COALESCE(p.name_cn,g.name_cn) ELSE n.name END AS name,
    CASE WHEN p.id IS NOT NULL THEN COALESCE(p.color,n.color) ELSE n.color END AS color,
    CASE WHEN p.id IS NOT NULL THEN p.image_object_key ELSE n.icon_object_key END AS icon_object_key,
    CASE WHEN p.id IS NOT NULL THEN p.image_fit ELSE n.icon_fit END AS icon_fit,
    CASE WHEN p.id IS NOT NULL THEN p.image_focal_x ELSE n.icon_focal_x END AS icon_focal_x,
    CASE WHEN p.id IS NOT NULL THEN p.image_focal_y ELSE n.icon_focal_y END AS icon_focal_y,
    CASE WHEN p.id IS NOT NULL THEN p.image_zoom ELSE n.icon_zoom END AS icon_zoom,
    CASE WHEN p.id IS NOT NULL THEN p.image_rotation ELSE n.icon_rotation END AS icon_rotation,
    CASE WHEN p.id IS NOT NULL THEN p.image_media_revision ELSE n.icon_media_revision END AS icon_media_revision,
