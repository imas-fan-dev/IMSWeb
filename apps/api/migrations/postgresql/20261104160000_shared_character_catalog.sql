    FOREIGN KEY (default_profile_id, id, default_project_id)
    REFERENCES catalog_character_project_profiles(id, character_id, project_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE FUNCTION catalog_ensure_default_profile() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE profile_id BIGINT;
BEGIN
    INSERT INTO catalog_character_project_profiles(character_id, project_id)
    VALUES (NEW.id, NEW.default_project_id)
    ON CONFLICT (character_id, project_id) DO UPDATE SET character_id=EXCLUDED.character_id
    RETURNING id INTO profile_id;
    UPDATE catalog_characters SET default_profile_id=profile_id WHERE id=NEW.id;
    RETURN NEW;
END $$;
CREATE TRIGGER catalog_character_default_profile AFTER INSERT OR UPDATE OF default_project_id
    ON catalog_characters FOR EACH ROW EXECUTE FUNCTION catalog_ensure_default_profile();

CREATE FUNCTION catalog_require_default_profile() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM catalog_characters WHERE id=NEW.id AND default_profile_id IS NULL) THEN
        RAISE EXCEPTION 'Character requires a default project profile' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER catalog_character_requires_default
    AFTER INSERT OR UPDATE OF default_profile_id ON catalog_characters
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION catalog_require_default_profile();

