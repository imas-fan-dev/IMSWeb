CREATE TABLE catalog_character_project_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES catalog_characters(id) ON DELETE RESTRICT,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
    name_cn TEXT CHECK (name_cn IS NULL OR (btrim(name_cn) <> '' AND length(name_cn) <= 120)),
    name_ja TEXT CHECK (name_ja IS NULL OR (btrim(name_ja) <> '' AND length(name_ja) <= 120)),
    name_en TEXT CHECK (name_en IS NULL OR (btrim(name_en) <> '' AND length(name_en) <= 160)),
    representative_color TEXT CHECK (representative_color IS NULL OR representative_color ~ '^#[0-9A-Fa-f]{6}$'),
    birth_month INTEGER,
    birth_day INTEGER,
    biography TEXT CHECK (biography IS NULL OR length(biography) <= 20000),
    voice_status TEXT NOT NULL DEFAULT 'unknown' CHECK (voice_status IN ('unknown', 'voiced', 'unvoiced')),
    profile_url TEXT,
    avatar_object_key TEXT,
    avatar_fit TEXT NOT NULL DEFAULT 'cover' CHECK (avatar_fit IN ('cover', 'contain')),
    avatar_focal_x DOUBLE PRECISION NOT NULL DEFAULT 0.5 CHECK (avatar_focal_x BETWEEN 0 AND 1),
    avatar_focal_y DOUBLE PRECISION NOT NULL DEFAULT 0.5 CHECK (avatar_focal_y BETWEEN 0 AND 1),
    avatar_zoom DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (avatar_zoom BETWEEN 1 AND 3),
    avatar_rotation INTEGER NOT NULL DEFAULT 0 CHECK (avatar_rotation IN (0,90,180,270)),
    avatar_media_revision INTEGER NOT NULL DEFAULT 0 CHECK (avatar_media_revision >= 0),
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (character_id, project_id),
    UNIQUE (id, character_id, project_id),
    UNIQUE (id, project_id),
    CHECK ((birth_month IS NULL AND birth_day IS NULL) OR
        (birth_month IS NOT NULL AND birth_day IS NOT NULL AND birth_month BETWEEN 1 AND 12
         AND birth_day BETWEEN 1 AND CASE birth_month WHEN 2 THEN 29 WHEN 4 THEN 30
             WHEN 6 THEN 30 WHEN 9 THEN 30 WHEN 11 THEN 30 ELSE 31 END))
);
CREATE INDEX catalog_character_profiles_project_idx ON catalog_character_project_profiles(project_id, character_id);
CREATE INDEX catalog_character_profiles_media_idx ON catalog_character_project_profiles(avatar_object_key) WHERE avatar_object_key IS NOT NULL;
