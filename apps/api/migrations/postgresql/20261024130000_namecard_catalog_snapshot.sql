  SELECT seed.name_ja, seed.name_cn, seed.name_en, seed.aliases, seed.display_order
  FROM unit_seed seed
  WHERE NOT EXISTS (
    SELECT 1 FROM public.namecard_units existing
    WHERE existing.deleted_at IS NULL AND existing.name_cn = seed.name_cn
  );
  GET DIAGNOSTICS unit_inserted = ROW_COUNT;

