-- ims:migration-phase: post-data
--
-- Wiki 增强 Markdown 文档基座（Ticket 01）。
--
-- `wiki_entries.content_mode` 是非破坏性双模式开关：存量 346 个条目继续使用
-- `structured`（默认值），切到 `document` 也不会删除 `wiki_story_cards` /
-- `wiki_story_links` 的任何一行。
--
-- `wiki_entry_documents` 保存当前文档原文、服务端编译好的版本化 AST 与派生
-- 纯文本；`wiki_entry_document_revisions` 保存历史快照，写入侧只保留每个条目
-- 最新 30 条。两张表都按 `wiki_entries(id)` / `projects(id)` 级联删除，避免
-- 内容页删除后残留孤儿文档。

-- The migration runner applies the whole catalog in one transaction. Earlier
-- data migrations update `wiki_entries` rows, which queues the deferred
-- `wiki_entry_name_integrity` constraint trigger; PostgreSQL refuses the
-- internal ALTER such a pending event blocks (adding the foreign keys below
-- touches `wiki_entries`). Flushing the queue first is safe here because this
-- is the last migration, then the deferred mode is restored for later ones.
SET CONSTRAINTS ALL IMMEDIATE;

ALTER TABLE public.wiki_entries
    ADD COLUMN content_mode TEXT NOT NULL DEFAULT 'structured'
        CHECK (content_mode IN ('structured', 'document'));

CREATE TABLE public.wiki_entry_documents (
    entry_id BIGINT PRIMARY KEY REFERENCES public.wiki_entries(id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    source_markdown TEXT NOT NULL DEFAULT '',
    compiled_ast JSONB NOT NULL DEFAULT '{"version":1,"headings":[],"availableTags":[],"blocks":[]}'::jsonb,
    plain_text TEXT NOT NULL DEFAULT '',
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    updated_by TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX wiki_entry_documents_project_idx
    ON public.wiki_entry_documents (project_id);

CREATE TABLE public.wiki_entry_document_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES public.wiki_entries(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL CHECK (revision >= 0),
    source_markdown TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (entry_id, revision)
);

SET CONSTRAINTS ALL DEFERRED;
