-- A 组合 (unit) is a searchable shortcut in the namecard picker: choosing one
-- expands into its member characters. The unit itself is never attached to a
-- card, so it needs no card-side foreign key and — unlike a character — it may
-- belong to several agencies, which is why the agency link is its own table
-- rather than a column.
--
-- Members are characters from the namecard catalog, never other units: nesting
-- is not supported.

CREATE TABLE IF NOT EXISTS public.namecard_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_cn TEXT NOT NULL,
    name_ja TEXT,
    name_en TEXT,
    aliases TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT namecard_units_created_by_fkey
        FOREIGN KEY (created_by) REFERENCES public.backoffice_accounts(id)
        ON DELETE SET NULL,
    CONSTRAINT namecard_units_updated_by_fkey
        FOREIGN KEY (updated_by) REFERENCES public.backoffice_accounts(id)
        ON DELETE SET NULL,
    CONSTRAINT namecard_units_name_cn_check
        CHECK (btrim(name_cn) <> '' AND length(name_cn) <= 120),
    CONSTRAINT namecard_units_name_ja_check
        CHECK (name_ja IS NULL OR (btrim(name_ja) <> '' AND length(name_ja) <= 120)),
    CONSTRAINT namecard_units_name_en_check
        CHECK (name_en IS NULL OR (btrim(name_en) <> '' AND length(name_en) <= 160)),
    CONSTRAINT namecard_units_aliases_check
        CHECK (aliases IS NULL OR length(aliases) <= 4000),
    CONSTRAINT namecard_units_display_order_check CHECK (display_order >= 0),
    CONSTRAINT namecard_units_revision_check CHECK (revision >= 0),
    CONSTRAINT namecard_units_updated_at_check CHECK (updated_at >= created_at),
    CONSTRAINT namecard_units_deleted_at_check
        CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

-- Unique among live rows only: retiring a unit must not reserve its name.
CREATE UNIQUE INDEX IF NOT EXISTS namecard_units_name_cn_key
    ON public.namecard_units (name_cn)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS namecard_units_order_idx
    ON public.namecard_units (display_order, id)
    WHERE deleted_at IS NULL;

-- The agencies a unit is filed under. Order is presentation order in the
-- picker's series tabs.
CREATE TABLE IF NOT EXISTS public.namecard_unit_agencies (
    unit_id BIGINT NOT NULL,
    agency_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT namecard_unit_agencies_pkey PRIMARY KEY (unit_id, agency_id),
    CONSTRAINT namecard_unit_agencies_unit_order_key UNIQUE (unit_id, display_order),
    CONSTRAINT namecard_unit_agencies_display_order_check CHECK (display_order >= 0),
    CONSTRAINT namecard_unit_agencies_unit_id_fkey
        FOREIGN KEY (unit_id) REFERENCES public.namecard_units(id) ON DELETE CASCADE,
    CONSTRAINT namecard_unit_agencies_agency_id_fkey
        FOREIGN KEY (agency_id) REFERENCES public.agencies(id)
);

CREATE INDEX IF NOT EXISTS namecard_unit_agencies_agency_idx
    ON public.namecard_unit_agencies (agency_id, unit_id);

-- Membership. RESTRICT on the character side matches the card link tables: a
-- character that still belongs to a unit cannot be hard-deleted.
CREATE TABLE IF NOT EXISTS public.namecard_unit_members (
    unit_id BIGINT NOT NULL,
    character_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT namecard_unit_members_pkey PRIMARY KEY (unit_id, character_id),
    CONSTRAINT namecard_unit_members_unit_order_key UNIQUE (unit_id, display_order),
    CONSTRAINT namecard_unit_members_display_order_check CHECK (display_order >= 0),
    CONSTRAINT namecard_unit_members_unit_id_fkey
        FOREIGN KEY (unit_id) REFERENCES public.namecard_units(id) ON DELETE CASCADE,
    CONSTRAINT namecard_unit_members_character_id_fkey
        FOREIGN KEY (character_id) REFERENCES public.namecard_characters(id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS namecard_unit_members_character_idx
    ON public.namecard_unit_members (character_id, unit_id);
