-- ims:migration-phase: post-data

-- The namecard candidate catalog gets its own table instead of extending the
-- Wiki `idols` table. Wiki storage is shaped by Wiki content needs — story
-- entries, per-agency storage slugs, the `entry_kind`/`entry_subtype` pairing —
-- while the namecard picker needs a different field set and a wider taxonomy:
-- staff, rivals, mascots, characters that only appear outside the games, and the
-- free-form aliases the community actually searches by. Keeping the two apart
-- means neither module has to absorb the other's constraints.
--
-- Card-side references still point at `idols` while this migration runs; the
-- expand/contract step that moves `fudaba_card_idols`, `namecard_idols` and
-- `fudaba_card_claim_idols` onto this table is a later migration in the same
-- chain, so nothing here changes an existing read or write path.

CREATE TABLE IF NOT EXISTS public.namecard_characters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    category TEXT NOT NULL DEFAULT 'idol',
    is_fallback BOOLEAN NOT NULL DEFAULT FALSE,
    name_cn TEXT NOT NULL,
    name_ja TEXT,
    name_en TEXT,
    aliases TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT namecard_characters_agency_id_fkey
        FOREIGN KEY (agency_id) REFERENCES public.agencies(id),
    CONSTRAINT namecard_characters_created_by_fkey
        FOREIGN KEY (created_by) REFERENCES public.backoffice_accounts(id)
        ON DELETE SET NULL,
    CONSTRAINT namecard_characters_updated_by_fkey
        FOREIGN KEY (updated_by) REFERENCES public.backoffice_accounts(id)
        ON DELETE SET NULL,
    -- `category` is the namecard-side taxonomy. It is deliberately not the Wiki
    -- `entry_kind`: a mascot or a staff member has no Wiki entry kind, and the
    -- two vocabularies must be free to move independently. The six values are
    -- also the order the picker's 分类 dropdown lists them in.
    CONSTRAINT namecard_characters_category_check
        CHECK (category IN ('idol', 'staff', 'rival', 'mascot', 'chara', 'other')),
    CONSTRAINT namecard_characters_name_cn_check
        CHECK (btrim(name_cn) <> '' AND length(name_cn) <= 120),
    CONSTRAINT namecard_characters_name_ja_check
        CHECK (name_ja IS NULL OR (btrim(name_ja) <> '' AND length(name_ja) <= 120)),
    CONSTRAINT namecard_characters_name_en_check
        CHECK (name_en IS NULL OR (btrim(name_en) <> '' AND length(name_en) <= 160)),
    -- One field holds every alias the entry answers to; the picker matches the
    -- whole blob, so no per-alias row is needed.
    CONSTRAINT namecard_characters_aliases_check
        CHECK (aliases IS NULL OR length(aliases) <= 4000),
    CONSTRAINT namecard_characters_display_order_check CHECK (display_order >= 0),
    CONSTRAINT namecard_characters_revision_check CHECK (revision >= 0),
    CONSTRAINT namecard_characters_updated_at_check CHECK (updated_at >= created_at),
    CONSTRAINT namecard_characters_deleted_at_check
        CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

-- A display name is unique inside one agency, but only among live rows: retiring
-- an entry must not permanently reserve its name.
CREATE UNIQUE INDEX IF NOT EXISTS namecard_characters_agency_name_key
    ON public.namecard_characters (agency_id, name_cn)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS namecard_characters_agency_order_idx
    ON public.namecard_characters (agency_id, display_order, id)
    WHERE deleted_at IS NULL;

-- At most one fallback bucket per category: it answers "what do we offer when a
-- search matches nothing for this category", so a second one is meaningless and
-- the picker could not choose between them. The lookup key and the uniqueness
-- are the same object.
CREATE UNIQUE INDEX IF NOT EXISTS namecard_characters_fallback_category_key
    ON public.namecard_characters (category)
    WHERE is_fallback AND deleted_at IS NULL;

-- The sentinel agency owns the 「其他…」 fallback buckets plus the entries that
-- belong to no major agency. A character row needs an agency, and 其他偶像
-- belongs to none of the real ones. `wiki_enabled = false` keeps the agency and
-- everything under it off every public Wiki surface; 其他 is the name the Wiki
-- admin list shows.
--
-- `display_order` 20000 keeps it last. The character catalog and the picker's
-- 企划 dropdown both order by that column and every real agency sits at 10000+,
-- so a seeded 9999 would put the fallbacks ahead of every real agency.
--
-- `code` stays `namecard-other`: it is the stable identifier and
-- `fudaba_cards.series_code` references it, so renaming it would be a separate,
-- card-touching decision.
--
-- The id is pinned so this row never consumes an identity value: the canonical
-- agencies are seeded with explicit ids starting at 1 (the Fudaba metadata
-- import and every test fixture that owns the agency table), and letting the
-- sequence hand the sentinel id 1 would collide with them.
INSERT INTO public.agencies (id, code, name_cn, color, wiki_enabled, display_order, banner_title)
SELECT 999999, 'namecard-other', '其他', '#8A8A8A', FALSE, 20000, ''
WHERE NOT EXISTS (SELECT 1 FROM public.agencies WHERE code = 'namecard-other');

-- One fallback per category, listed in category order. `现实人物` answers the
-- `other` bucket: people who are not idols, staff, rivals, mascots or
-- characters. Only the display names live here; the stored category values are
-- what the rest of the system references.
INSERT INTO public.namecard_characters (agency_id, category, is_fallback, name_cn, display_order)
SELECT agency.id, bucket.category, TRUE, bucket.name_cn, bucket.display_order
FROM public.agencies AS agency
CROSS JOIN (VALUES
    ('idol'::text, '其他偶像'::text, 0),
    ('staff'::text, '其他职员'::text, 1),
    ('rival'::text, '其他对手'::text, 2),
    ('mascot'::text, '其他吉祥物'::text, 3),
    ('chara'::text, '其他角色'::text, 4),
    ('other'::text, '现实人物'::text, 5)
) AS bucket(category, name_cn, display_order)
WHERE agency.code = 'namecard-other'
  AND NOT EXISTS (
      SELECT 1
      FROM public.namecard_characters AS existing
      WHERE existing.agency_id = agency.id
        AND existing.is_fallback
        AND existing.category = bucket.category
  );
