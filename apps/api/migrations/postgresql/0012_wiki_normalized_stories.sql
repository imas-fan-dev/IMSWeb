CREATE TABLE public.wiki_story_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    idol_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    card_name TEXT NOT NULL,
    subtitle TEXT,
    image_file TEXT,
    display_order INTEGER NOT NULL CHECK (display_order >= 0),
    UNIQUE (id, agency_id),
    UNIQUE (agency_id, idol_id, category_id, card_name),
    FOREIGN KEY (agency_id, idol_id, category_id)
        REFERENCES public.wiki_idol_categories(agency_id, idol_id, category_id)
        ON DELETE CASCADE
);

CREATE INDEX wiki_story_cards_agency_idol_idx
    ON public.wiki_story_cards(agency_id, idol_id, display_order);
CREATE INDEX wiki_story_cards_category_idx
    ON public.wiki_story_cards(category_id);
CREATE INDEX wiki_story_cards_background_idx
    ON public.wiki_story_cards(category_id, id) WHERE image_file IS NOT NULL;

CREATE TABLE public.wiki_story_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL,
    card_id BIGINT NOT NULL,
    up_name TEXT,
    video_title TEXT,
    url TEXT,
    display_order INTEGER NOT NULL CHECK (display_order >= 0),
    legacy_table TEXT,
    legacy_id BIGINT,
    legacy_subtitle TEXT,
    legacy_image_file TEXT,
    UNIQUE (card_id, display_order),
    UNIQUE (legacy_table, legacy_id),
    CHECK ((legacy_table IS NULL) = (legacy_id IS NULL)),
    FOREIGN KEY (card_id, agency_id)
        REFERENCES public.wiki_story_cards(id, agency_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX wiki_story_links_agency_api_id_idx
    ON public.wiki_story_links(agency_id, COALESCE(legacy_id, id));
CREATE INDEX wiki_story_links_card_idx
    ON public.wiki_story_links(card_id, display_order);

WITH legacy_rows AS (
    SELECT '765'::text AS agency_code, '765_stories'::text AS legacy_table, s.*
    FROM public."765_stories" s
    UNION ALL
    SELECT '876', '876_stories', s.* FROM public."876_stories" s
    UNION ALL
    SELECT 'cg', 'cg_stories', s.* FROM public.cg_stories s
    UNION ALL
    SELECT 'ml', 'ml_stories', s.* FROM public.ml_stories s
    UNION ALL
    SELECT 'sidem', 'sidem_stories', s.* FROM public.sidem_stories s
    UNION ALL
    SELECT 'sc', 'sc_stories', s.* FROM public.sc_stories s
    UNION ALL
    SELECT 'gk', 'gk_stories', s.* FROM public.gk_stories s
), resolved AS (
    SELECT a.id AS agency_id, rows.id AS legacy_id, rows.idol_id,
           c.id AS category_id, rows.card_name, rows.subtitle, rows.image_file
    FROM legacy_rows rows
    JOIN public.agencies a ON a.code = rows.agency_code
    JOIN public.idols i ON i.id = rows.idol_id AND i.agency_id = a.id
    JOIN public.wiki_categories c
      ON c.agency_id = a.id AND c.name = rows.category
), grouped AS (
    SELECT agency_id, idol_id, category_id, card_name,
           (ARRAY_AGG(subtitle ORDER BY legacy_id))[1] AS subtitle,
           (ARRAY_AGG(image_file ORDER BY legacy_id))[1] AS image_file,
           MIN(legacy_id) AS first_legacy_id
    FROM resolved
    GROUP BY agency_id, idol_id, category_id, card_name
), ordered AS (
    SELECT grouped.*,
           ROW_NUMBER() OVER (
               PARTITION BY idol_id, category_id
               ORDER BY first_legacy_id, card_name
           ) - 1 AS display_order
    FROM grouped
)
INSERT INTO public.wiki_story_cards
    (agency_id, idol_id, category_id, card_name, subtitle, image_file, display_order)
SELECT agency_id, idol_id, category_id, card_name, subtitle, image_file,
       display_order::integer
FROM ordered
ORDER BY agency_id, idol_id, category_id, display_order;

WITH legacy_rows AS (
