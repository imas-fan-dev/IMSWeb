import { z } from "zod"
import {
  errorResponseSchema,
  exactJsonResponse,
  failureMessageResponseSchema,
  legacyStripRequestObject,
  messageErrorResponseSchema,
  successEnvelope,
} from "./common.js"

export const sitePackageRuntimeModeSchema = z.enum(["safe", "isolated-script"])

export const sitePackageRevisionStateSchema = z.enum(["ready", "archived"])

export const sitePackageRevisionSchema = exactJsonResponse({
  id: z.string().uuid(),
  packageId: z.string().uuid(),
  revisionNumber: z.number().int().positive(),
  entryPath: z.string(),
  runtimeMode: sitePackageRuntimeModeSchema,
  state: sitePackageRevisionStateSchema,
  fileCount: z.number().int().nonnegative(),
  totalBytes: z.number().int().nonnegative(),
  sourceSha256: z.string().regex(/^[a-f0-9]{64}$/),
  createdBy: z.number().int().positive(),
  createdAt: z.number().int().nonnegative(),
  publishedAt: z.number().int().nonnegative().nullable(),
})

export const sitePackageSchema = exactJsonResponse({
  id: z.string().uuid(),
  slug: z.string(),
  title: z.string(),
  description: z.string(),
  publishedRevisionId: z.string().uuid().nullable(),
  createdBy: z.number().int().positive(),
  updatedBy: z.number().int().positive(),
  createdAt: z.number().int().nonnegative(),
  updatedAt: z.number().int().nonnegative(),
  contentOrigin: z.string().url(),
  revisions: z.array(sitePackageRevisionSchema),
})

export const sitePackageListSchema = exactJsonResponse({
  packages: z.array(sitePackageSchema),
})

const sitePackageUploadFields = {
  previewUrl: z.string().url(),
  previewToken: z.string().min(1),
  warnings: z.array(z.string()),
  hasScripts: z.boolean(),
}

export const sitePackageCreateResultSchema = successEnvelope({
  packageId: z.string().uuid(),
  revisionId: z.string().uuid(),
  ...sitePackageUploadFields,
})

export const sitePackageCreateRevisionResultSchema = successEnvelope({
  revision: sitePackageRevisionSchema,
  ...sitePackageUploadFields,
})

export const sitePackagePublishResultSchema = successEnvelope({
  packageId: z.string().uuid(),
  revisionId: z.string().uuid(),
  publishedAt: z.number().int().nonnegative().nullable(),
  operation: z.enum(["publish", "rollback", "noop"]),
})

export const sitePackagePreviewResultSchema = successEnvelope({
  previewToken: z.string().min(1),
  packageId: z.string().uuid(),
  revisionId: z.string().uuid(),
  previewUrl: z.string().url(),
})

export const sitePackageDeleteRevisionResultSchema = successEnvelope({
  packageId: z.string().uuid(),
  revisionId: z.string().uuid(),
  revisionNumber: z.number().int().positive(),
  packageDeleted: z.boolean(),
  objectCleanup: z.literal("queued"),
})

export const publicSitePackageSchema = exactJsonResponse({
  slug: z.string(),
  title: z.string(),
  description: z.string(),
  revisionId: z.string().uuid(),
  revisionNumber: z.number().int().positive(),
  runtimeMode: sitePackageRuntimeModeSchema,
  publishedAt: z.number().int().nonnegative(),
  siteUrl: z.string().url(),
  contentUrl: z.string().url(),
})

export const sitePackageIdParamsSchema = legacyStripRequestObject({
  id: z.string().optional(),
})

export const sitePackageRevisionParamsSchema = legacyStripRequestObject({
  id: z.string().optional(),
  revisionId: z.string().optional(),
})

export const publicSitePackageParamsSchema = legacyStripRequestObject({
  slug: z.string().optional(),
})

export const publishedSitePackageParamsSchema = legacyStripRequestObject({
  slug: z.string().optional(),
  revisionId: z.string().optional(),
})

export const previewSitePackageParamsSchema = legacyStripRequestObject({
  previewToken: z.string().optional(),
})

export const siteContentCacheBusterQuerySchema = legacyStripRequestObject({
  v: z.string().optional(),
})

export const sitePackageErrorResponseSchema = errorResponseSchema

export const sitePackageHttpErrorSchema = z.union([
  sitePackageErrorResponseSchema,
  messageErrorResponseSchema,
  failureMessageResponseSchema,
])

export type SitePackageRuntimeMode = z.infer<
  typeof sitePackageRuntimeModeSchema
>

export type SitePackageRevision = z.infer<typeof sitePackageRevisionSchema>

export type SitePackage = z.infer<typeof sitePackageSchema>

export type PublicSitePackage = z.infer<typeof publicSitePackageSchema>

export type SitePackageCreateResult = z.infer<
  typeof sitePackageCreateResultSchema
>

export type SitePackageCreateRevisionResult = z.infer<
  typeof sitePackageCreateRevisionResultSchema
>

export type SitePackageList = z.infer<typeof sitePackageListSchema>

export type SitePackagePublishResult = z.infer<
  typeof sitePackagePublishResultSchema
>

export type SitePackagePreviewResult = z.infer<
  typeof sitePackagePreviewResultSchema
>

export type SitePackageDeleteRevisionResult = z.infer<
  typeof sitePackageDeleteRevisionResultSchema
>

export type SitePackageIdParams = z.infer<typeof sitePackageIdParamsSchema>

export type SitePackageRevisionParams = z.infer<
  typeof sitePackageRevisionParamsSchema
>

export type PublicSitePackageParams = z.infer<
  typeof publicSitePackageParamsSchema
>

export type PublishedSitePackageParams = z.infer<
  typeof publishedSitePackageParamsSchema
>

export type PreviewSitePackageParams = z.infer<
  typeof previewSitePackageParamsSchema
>

export type SiteContentCacheBusterQuery = z.infer<
  typeof siteContentCacheBusterQuerySchema
>

export type SitePackageErrorResponse = z.infer<
  typeof sitePackageErrorResponseSchema
>

export type SitePackageHttpError = z.infer<
  typeof sitePackageHttpErrorSchema
>
